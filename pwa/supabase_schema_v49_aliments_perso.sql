-- v49 — Mes aliments et mes recettes
-- ════════════════════════════════════════════════════════════════
-- Un aliment à soi (valeurs de l'étiquette) ou une recette (ingrédients
-- pesés, nombre de parts), saisi une fois et ajouté ensuite comme
-- n'importe quel aliment (core/nutrition_recettes.py). Une ligne par
-- aliment :
--
--   nom      le nom affiché et cherché (unique par compte, casse ignorée :
--            le code le vérifie avant d'écrire) ;
--   food     valeurs pour 100 g {n, k, p, c, f, u} — le même format que
--            nutrition.food (v40), recalculé par le serveur ;
--   recette  pour une recette seulement : {ingredients, parts, poids_cuit,
--            poids_cru}, de quoi la rouvrir et la corriger. Vide pour un
--            aliment simple.
--
-- Les repas déjà notés gardent leur copie des valeurs (nutrition.food) :
-- corriger une recette ne réécrit pas le passé.
--
-- Fermée au navigateur comme les autres tables (v38). Sans cette table,
-- l'app marche comme avant : la page « Mes recettes et aliments » dit
-- qu'elle n'est pas encore prête, et /admin signale la migration manquante.
--
-- À exécuter dans l'éditeur SQL de Supabase. Idempotent.

create table if not exists public.aliments_perso (
  id          bigint generated by default as identity primary key,
  user_id     uuid not null references auth.users (id) on delete cascade,
  nom         text not null check (char_length(nom) between 1 and 80),
  food        jsonb not null check (jsonb_typeof(food) = 'object'),
  recette     jsonb check (recette is null or jsonb_typeof(recette) = 'object'),
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

-- La page et la recherche lisent les aliments d'un compte, les derniers
-- modifiés d'abord.
create index if not exists aliments_perso_user_idx
  on public.aliments_perso (user_id, updated_at desc);

alter table public.aliments_perso enable row level security;
revoke all on public.aliments_perso from anon, authenticated;
grant select, insert, update, delete on public.aliments_perso to service_role;

comment on table public.aliments_perso is
  'Aliments et recettes saisis par l''utilisateur (v49) : valeurs pour 100 g, ingrédients d''une recette.';

-- PostgREST garde le schéma en cache : sans ce rechargement, la table
-- reste invisible à l'API pendant quelques minutes.
notify pgrst, 'reload schema';
