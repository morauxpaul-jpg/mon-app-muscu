# Catégories reléguées en fin de résultats : quand on tape « poulet » on veut
# le blanc de poulet avant le wrap ou le curry.
_LOW_PRIORITY = {"Plats & fast-food", "Snacks & sucré"}


def build_foods():
    """Liste de dicts prête à sérialiser : {n, k, p, c, f, g, r, u:[[label, g], ...]}
    (clés courtes : le tableau est embarqué dans la page Nutrition).
    g = catégorie, r = rang de tri (0 = aliment simple, 1 = plat/snack)."""
    out = []
    cat = ""
    for entry in FOODS_RAW:
        if isinstance(entry, str):
            cat = entry
            continue
        name, kcal, p, c, f, portions = entry
        units = [[lbl, int(g)] for lbl, g in portions]
        if not any(int(g) == 100 for _, g in portions):
            units.append(["100 g", 100])
        out.append({"n": name, "k": kcal, "p": p, "c": c, "f": f, "g": cat,
                    "r": 1 if cat in _LOW_PRIORITY else 0, "u": units})
    return out


FOODS = build_foods()
