-- v52 — Amis : demandes, fil des séances terminées, encouragements
-- ════════════════════════════════════════════════════════════════
-- Choix du propriétaire (25/10/2026) : « Amis + séances visibles »,
-- visibles des amis ACCEPTÉS seulement, gratuit pour tous.
--
--   1. `amities` : une ligne par paire de comptes, quel que soit le sens.
--      En attente tant que l'autre n'a pas accepté. Refuser, annuler ou
--      retirer efface la ligne : l'effet est immédiat des deux côtés.
--   2. `fil_seances` : ce qu'un ami voit d'une séance TERMINÉE, et rien
--      d'autre — nom, date, durée, tonnage, records battus. Écrite par
--      /seance/finish. Ni poids du corps, ni photos, ni nutrition, ni
--      coach, ni note ni commentaire de séance : ces données ne sont pas
--      dans la table, le fil ne peut donc pas les montrer.
--   3. `encouragements` : un par personne et par séance (unicité), sur
--      une séance du fil (clé étrangère : la séance effacée, ses
--      encouragements partent avec).
--   4. `profiles.seances_masquees` : « Masquer mes séances ». Les amis ne
--      voient plus rien, l'amitié reste.
--
-- Fermées au navigateur comme les autres tables (v38) : RLS active, AUCUNE
-- règle, aucun droit pour anon et authenticated. Le navigateur n'a donc
-- accès à aucune ligne, même pas aux siennes. Seul le serveur (clé
-- service_role) lit et écrit ; il applique la règle de visibilité (amitié
-- acceptée, séances non masquées) dans core/db_amis.py, testée dans
-- tests/test_amis.py. Une règle « self » pour authenticated rouvrirait la
-- porte que la v38 a fermée.
--
-- Effacées avec le compte : core/db_admin.py les supprime, et les clés
-- étrangères aussi si le compte disparaît autrement.
--
-- Sans cette migration, l'app marche comme avant : la page Amis dit
-- qu'elle arrive bientôt, la fin de séance n'écrit rien dans le fil, et
-- /admin signale les tables manquantes.
--
-- À exécuter dans l'éditeur SQL de Supabase. Idempotent.

create table if not exists public.amities (
  id            bigint generated by default as identity primary key,
  demandeur     uuid not null references auth.users (id) on delete cascade,
  destinataire  uuid not null references auth.users (id) on delete cascade,
  etat          text not null default 'en_attente' check (etat in ('en_attente', 'acceptee')),
  created_at    timestamptz not null default now(),
  acceptee_le   timestamptz,
  constraint amities_pas_soi_meme check (demandeur <> destinataire),
  constraint amities_acceptee_datee check ((etat = 'acceptee') = (acceptee_le is not null))
);

-- Une seule ligne par paire, dans un sens ou dans l'autre : A→B interdit
-- B→A tant que la première existe.
create unique index if not exists amities_une_par_paire
  on public.amities (least(demandeur, destinataire), greatest(demandeur, destinataire));
create index if not exists amities_demandeur_idx on public.amities (demandeur);
create index if not exists amities_destinataire_idx on public.amities (destinataire);

create table if not exists public.fil_seances (
  id          bigint generated by default as identity primary key,
  user_id     uuid not null references auth.users (id) on delete cascade,
  session_id  uuid not null,
  date        date not null,
  seance      text not null check (char_length(seance) between 1 and 80),
  duree_min   integer check (duree_min is null or duree_min between 1 and 600),
  tonnage     numeric not null default 0 check (tonnage >= 0),
  records     jsonb not null default '[]'::jsonb check (jsonb_typeof(records) = 'array'),
  created_at  timestamptz not null default now(),
  constraint fil_seances_une_par_seance unique (user_id, session_id)
);

-- Le fil lit les séances récentes d'une liste de comptes.
create index if not exists fil_seances_user_date_idx
  on public.fil_seances (user_id, date desc);

create table if not exists public.encouragements (
  id            bigint generated by default as identity primary key,
  auteur        uuid not null references auth.users (id) on delete cascade,
  destinataire  uuid not null,
  session_id    uuid not null,
  created_at    timestamptz not null default now(),
  constraint encouragements_un_par_personne unique (auteur, session_id),
  constraint encouragements_pas_soi_meme check (auteur <> destinataire),
  constraint encouragements_seance_du_fil foreign key (destinataire, session_id)
    references public.fil_seances (user_id, session_id) on delete cascade
);
create index if not exists encouragements_session_idx on public.encouragements (session_id);
create index if not exists encouragements_destinataire_idx on public.encouragements (destinataire);

alter table public.profiles
  add column if not exists seances_masquees boolean not null default false;

comment on table public.amities is
  'Amis (v52) : une ligne par paire, en_attente puis acceptee ; effacée au refus ou au retrait.';
comment on table public.fil_seances is
  'Séances terminées visibles des amis acceptés (v52) : nom, date, durée, tonnage, records. Rien d''autre.';
comment on table public.encouragements is
  'Encouragements (v52) : un par personne et par séance du fil.';
comment on column public.profiles.seances_masquees is
  'Masquer mes séances (v52) : les amis ne voient plus rien, l''amitié reste.';

alter table public.amities enable row level security;
alter table public.fil_seances enable row level security;
alter table public.encouragements enable row level security;
revoke all on public.amities, public.fil_seances, public.encouragements from anon, authenticated;
grant select, insert, update, delete on public.amities, public.fil_seances, public.encouragements
  to service_role;

-- PostgREST garde le schéma en cache : sans ce rechargement, les tables
-- restent invisibles à l'API pendant quelques minutes.
notify pgrst, 'reload schema';

