-- v53 — Défis entre amis : le défi et ses participants
-- ════════════════════════════════════════════════════════════════
-- Choix du propriétaire (26/10/2026) : « Défis entre amis », gratuit pour
-- tous. Trois types (régularité, volume, progression sur un exercice),
-- trois durées (1, 2 ou 4 semaines), entre amis ACCEPTÉS.
--
--   1. `defis` : ce qui a été lancé — type, exercice (progression
--      seulement), durée, dates. Rien d'autre.
--   2. `defis_participants` : qui est invité, qui a accepté. Refuser
--      efface la ligne.
--
-- LE SCORE N'EST JAMAIS STOCKÉ. Il est recalculé à chaque lecture depuis
-- `history` (core/defis.py) : il n'y a aucun chiffre à modifier pour
-- tricher, et une séance effacée sort du score.
--
-- Fermées au navigateur comme les autres tables (v38, v52) : RLS active,
-- AUCUNE règle, aucun droit pour anon et authenticated. Le navigateur n'a
-- accès à aucune ligne, même pas aux siennes. Seul le serveur (clé
-- service_role) lit et écrit ; il applique la règle (core/db_defis.py,
-- testée dans tests/test_defis.py) :
--   - seuls les participants voient un défi ;
--   - on n'invite que ses amis acceptés, et un participant qui n'est plus
--     l'ami accepté du créateur sort du défi ;
--   - un ami qui a masqué ses séances reste dans le classement, sans aucun
--     détail de ses séances.
--
-- Effacées avec le compte : core/db_admin.py les supprime (le défi lancé
-- par ce compte part avec ses participants), et les clés étrangères aussi
-- si le compte disparaît autrement.
--
-- Sans cette migration, l'app marche comme avant : la page Amis dit que
-- les défis arrivent bientôt, l'accueil n'affiche pas de classement, et
-- /admin signale les tables manquantes.
--
-- À exécuter dans l'éditeur SQL de Supabase. Idempotent.

create table if not exists public.defis (
  id          bigint generated by default as identity primary key,
  createur    uuid not null references auth.users (id) on delete cascade,
  type        text not null check (type in ('regularite', 'volume', 'progression')),
  exercice    text check (exercice is null or char_length(exercice) between 1 and 80),
  semaines    smallint not null check (semaines in (1, 2, 4)),
  debut       date not null,
  fin         date not null,
  created_at  timestamptz not null default now(),
  constraint defis_fin_selon_duree check (fin = debut + (semaines * 7 - 1)),
  constraint defis_exercice_si_progression check ((type = 'progression') = (exercice is not null))
);
create index if not exists defis_createur_idx on public.defis (createur);

create table if not exists public.defis_participants (
  id          bigint generated by default as identity primary key,
  defi_id     bigint not null references public.defis (id) on delete cascade,
  user_id     uuid not null references auth.users (id) on delete cascade,
  etat        text not null default 'invite' check (etat in ('invite', 'acceptee')),
  created_at  timestamptz not null default now(),
  repondu_le  timestamptz,
  constraint defis_participants_un_par_defi unique (defi_id, user_id),
  constraint defis_participants_acceptee_datee check ((etat = 'acceptee') = (repondu_le is not null))
);
-- « Mes défis » : les lignes d'un compte.
create index if not exists defis_participants_user_idx on public.defis_participants (user_id);

comment on table public.defis is
  'Défis entre amis (v53) : type, exercice, durée, dates. Le score n''est pas stocké : recalculé depuis history.';
comment on table public.defis_participants is
  'Participants d''un défi (v53) : invite puis acceptee ; refuser efface la ligne.';

alter table public.defis enable row level security;
alter table public.defis_participants enable row level security;
revoke all on public.defis, public.defis_participants from anon, authenticated;
grant select, insert, update, delete on public.defis, public.defis_participants to service_role;

-- PostgREST garde le schéma en cache : sans ce rechargement, les tables
-- restent invisibles à l'API pendant quelques minutes.
notify pgrst, 'reload schema';

