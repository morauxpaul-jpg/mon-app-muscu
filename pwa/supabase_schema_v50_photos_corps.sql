-- v50 — Photos de progression (PRO)
-- ════════════════════════════════════════════════════════════════
-- Des photos de son corps, de face, de profil et de dos, pour voir
-- l'évolution (demande du propriétaire, 18/10/2026). Deux morceaux :
--
--   1. la table `photos_corps` : une ligne par photo, ce que la page liste
--      et compare (date, angle, chemin du fichier). Une seule photo par
--      angle et par jour : en reprendre une la remplace.
--   2. le dossier `photos-corps` de Supabase Storage, où sont les fichiers.
--      PRIVÉ : aucune adresse publique, aucune règle pour le navigateur.
--      Seul le serveur (clé service_role) lit et écrit ; il vérifie à
--      chaque photo qu'elle appartient au compte connecté.
--
-- Les fichiers arrivent déjà réduits par le navigateur (1 600 px au plus,
-- JPEG, sans les métadonnées de l'appareil photo, donc sans position GPS),
-- avec une miniature de 400 px. 2 Mo au plus par fichier.
--
-- Effacées avec le compte : le serveur supprime les fichiers puis les
-- lignes (core/db_admin.py) ; la clé étrangère efface les lignes si le
-- compte disparaît autrement.
--
-- Fermée au navigateur comme les autres tables (v38). Sans cette
-- migration, l'app marche comme avant : la page Photos dit qu'elle n'est
-- pas encore prête, et /admin signale la table manquante.
--
-- À exécuter dans l'éditeur SQL de Supabase. Idempotent. Le dossier n'est
-- créé que si le schéma `storage` existe (toujours vrai chez Supabase ;
-- faux sur le PostgreSQL nu où la CI rejoue les migrations).

create table if not exists public.photos_corps (
  id          bigint generated by default as identity primary key,
  user_id     uuid not null references auth.users (id) on delete cascade,
  date        date not null,
  angle       text not null check (angle in ('face', 'profil', 'dos')),
  chemin      text not null unique check (char_length(chemin) between 1 and 200),
  miniature   text not null check (char_length(miniature) between 1 and 200),
  octets      integer not null check (octets > 0),
  created_at  timestamptz not null default now(),
  constraint photos_corps_un_par_angle_et_jour unique (user_id, date, angle)
);

-- La page lit les photos d'un compte, les plus récentes d'abord.
create index if not exists photos_corps_user_date_idx
  on public.photos_corps (user_id, date desc);

alter table public.photos_corps enable row level security;
revoke all on public.photos_corps from anon, authenticated;
grant select, insert, update, delete on public.photos_corps to service_role;

comment on table public.photos_corps is
  'Photos de progression (v50) : date, angle (face, profil, dos), fichiers dans le dossier privé photos-corps.';

do $$
begin
  if to_regclass('storage.buckets') is not null then
    insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
    values ('photos-corps', 'photos-corps', false, 2097152, array['image/jpeg'])
    on conflict (id) do update
      set public = false,
          file_size_limit = excluded.file_size_limit,
          allowed_mime_types = excluded.allowed_mime_types;
  end if;
end $$;

-- PostgREST garde le schéma en cache : sans ce rechargement, la table
-- reste invisible à l'API pendant quelques minutes.
notify pgrst, 'reload schema';
